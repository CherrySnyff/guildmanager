    {
        $map = [
            'despised' => 'Когда члены вашей гильдии находятся на территории фракции, выполняют её задание или взаимодействуют с её представителями, они не могут использовать Дипломатию и Выступление против членов фракции. КС Обмана становится невероятно трудным: +10 к КС, а представители фракции используют «Понять намерения» на каждую проверку Обмана. Все представители фракции считаются враждебными.',
            'hated' => 'Когда члены вашей гильдии находятся на территории фракции, выполняют её задание или взаимодействуют с её представителями, КС проверок Дипломатии, Обмана и Выступления становится невероятно трудным: +10 к КС. Все представители фракции считаются недружественными.',
            'wanted' => 'Когда члены вашей гильдии находятся на территории фракции, выполняют её задание или взаимодействуют с её представителями, КС проверок Дипломатии, Обмана и Выступления становится очень трудным: +5 к КС.',
            'suspicious' => 'Когда члены вашей гильдии находятся на территории фракции, выполняют её задание или взаимодействуют с её представителями, КС проверок Дипломатии, Обмана и Выступления становится трудным: +2 к КС.',
            'neutral' => 'Представители фракции относятся к членам вашей гильдии безразлично. Проверки проходят без дополнительных модификаторов репутации.',
            'friendly' => 'Когда члены вашей гильдии находятся на территории фракции, выполняют её задание или взаимодействуют с её представителями, КС проверок Дипломатии, Обмана и Выступления становится лёгким: -2 к КС.',
            'promising' => 'Когда члены вашей гильдии находятся на территории фракции, выполняют её задание или взаимодействуют с её представителями, КС проверок Дипломатии, Обмана и Выступления становится очень лёгким: -5 к КС.',
            'hero' => 'Когда члены вашей гильдии находятся на территории фракции, выполняют её задание или взаимодействуют с её представителями, КС проверок Дипломатии, Обмана и Выступления становится невероятно лёгким: -10 к КС. Все представители фракции считаются дружественными.',
            'legend' => 'Когда члены вашей гильдии находятся на территории фракции, выполняют её задание или взаимодействуют с её представителями, КС проверок Дипломатии, Обмана и Выступления становится невероятно лёгким: -10 к КС. Рядовые представители фракции готовы выполнять простые Просьбы без проверки и обычно не используют «Понять намерения» из-за высокого доверия. Попытка Принуждения сразу снижает репутацию гильдии на 10 очков. Все представители фракции считаются любезными.',
        ];

        return $map[$class] ?? '';
    }

    /**
     * @return array<string, string>
     */
    public static function organizationSizeRu(string $enLabel): string
    {
        $map = [
            'Small' => 'Малая',
            'Medium' => 'Средняя',
            'Large' => 'Большая',
            'Legendary' => 'Легендарная',
        ];

        return $map[$enLabel] ?? $enLabel;
    }

    /**
     * Стадия размера по фактическому уровню организации (ТЗ):
     * 1–5 Малая, 6–15 Средняя, 16–19 Большая, 20 Легендарная.
     */
    public static function organizationSizeEnFromLevel(int $organizationLevel): string
    {
        if ($organizationLevel <= 5) {
            return 'Small';
        }
        if ($organizationLevel <= 15) {
            return 'Medium';
        }
        if ($organizationLevel <= 19) {
            return 'Large';
        }

        return 'Legendary';
    }
}
