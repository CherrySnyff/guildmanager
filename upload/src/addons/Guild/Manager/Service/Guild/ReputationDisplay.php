<?php

namespace Guild\Manager\Service\Guild;

/**
 * Чистые функции представления данных репутации и организации без обращений к БД.
 *
 * - relation* — шкала отношения фракции к сумме репутации во вкладке «Репутация»;
 * - organizationSizeRu / organizationSizeEnFromLevel — подпись размера организации для UI (RU по EN-хранилищу в БД или от уровня).
 */
class ReputationDisplay
{
    public static function relationClass(int $sum): string
    {
        if ($sum <= -100) {
            return 'despised';
        }
        if ($sum >= -99 && $sum <= -70) {
            return 'hated';
        }
        if ($sum >= -69 && $sum <= -40) {
            return 'wanted';
        }
        if ($sum >= -39 && $sum <= -11) {
            return 'suspicious';
        }
        if ($sum >= -10 && $sum <= 10) {
            return 'neutral';
        }
        if ($sum >= 11 && $sum <= 39) {
            return 'friendly';
        }
        if ($sum >= 40 && $sum <= 69) {
            return 'promising';
        }
        if ($sum >= 70 && $sum <= 99) {
            return 'hero';
        }

        return 'legend';
    }

    public static function relationLabel(int $sum): string
    {
        if ($sum <= -100) {
            return 'Презренный';
        }
        if ($sum >= -99 && $sum <= -70) {
            return 'Ненавистный';
        }
        if ($sum >= -69 && $sum <= -40) {
            return 'Разыскиваемый';
        }
        if ($sum >= -39 && $sum <= -11) {
            return 'Подозрительный';
        }
        if ($sum >= -10 && $sum <= 10) {
            return 'Нейтральный';
        }
        if ($sum >= 11 && $sum <= 39) {
            return 'Дружественный';
        }
        if ($sum >= 40 && $sum <= 69) {
            return 'Подающий надежды';
        }
        if ($sum >= 70 && $sum <= 99) {
            return 'Герой';
        }

        return 'Легенда';
    }

